(def ^:private unreadable ::unreadable)

(defn- read-projection [ws product]
  (when-let [root (:file ws)]
    (let [f (io/file root (projection-path product))]
      (when (.isFile f)
        (try (edn/read-string (slurp f))
             (catch Exception _ unreadable))))))

;; The projection's datoms are NOT passed through to the client. Namespaces are
;; dropped on the wire (`clojure.data.json` writes `:canvas/id` as `id`), and the
;; datoms have three pairs that collide once stripped:
;;
;;   :db/id     + :canvas/id  -> id
;;   :hyp/status + :gate/status -> status
;;   :hyp/evidence + :gate/evidence -> evidence
;;
;; A colliding pair does not error — one silently wins, by map iteration order —
;; and the two `status` values are exactly the pair this view exists to show
;; separately: what the ledger says about a hypothesis versus what the metrics
;; say. So the shape is re-keyed here, explicitly, and a test asserts that no two
;; keys in it strip to the same name.

(defn- kw->str
  "A keyword as its full name, namespace included.

  Keyword VALUES lose their namespace on the wire the same way keys do, so
  `:hyp/t1` would arrive as `t1` and `:lean/problem` as `problem`. The ids are
  what a proposal names and what a reader copies into a `gftd` command, so they
  travel as strings that survive intact."
  [k]
  (when k (str (symbol k))))

(defn- block->wire [b]
  (cond-> {:id (kw->str (:canvas/id b))
           :block (kw->str (:canvas/block b))
           :label (:canvas/label b)
           :order (:canvas/order b)
           :items (vec (:canvas/items b))}
    (:canvas/note b) (assoc :note (:canvas/note b))))

(defn- hyp->wire [h]
  (cond-> {:id (kw->str (:hyp/id h))
           :claim (:hyp/claim h)
           :gate (:hyp/gate h)
           :risk (:hyp/risk h)
           :status (:hyp/status h)}
    (:hyp/evidence h) (assoc :evidence (:hyp/evidence h))
    (:gate/status h) (assoc :gate-status (:gate/status h))
    (:gate/distance h) (assoc :gate-distance (:gate/distance h))
    (:gate/evidence h) (assoc :gate-evidence (:gate/evidence h))
    (seq (:gate/needs h)) (assoc :gate-needs (vec (:gate/needs h)))))

(defn- proposal->wire [p state]
  {:id (:proposal/id p)
   :business-id (:proposal/business-id p)
   :action (:proposal/action p)
   :canvas-id (:proposal/canvas-id p)
   :value (:proposal/value p)
   :reason (:proposal/reason p)
   :proposed-by (:proposal/proposed-by p)
   :proposed-at (:proposal/proposed-at p)
   :withdrawn-by (:proposal/withdrawn-by p)
   :withdrawn-at (:proposal/withdrawn-at p)
   :state state})

(defn- riskiest
  "The hypothesis the canvas itself marks as riskiest, or nil.

  Not 'the first one' and not a guess: `:hyp/risk :riskiest` is a field the
  portfolio datoms carry, and a canvas that never marked one gets no highlight
  rather than an arbitrary block lit up."
  [hyps]
  (first (filter #(= :riskiest (:hyp/risk %)) hyps)))

(defn canvas
  "The folded canvas of `b`, or the reason there is none.

  `:state` mirrors the face states in `business`: `:unbound` (this business has
  no `:canvas/product`), `:unresolvable` (it has one, but no workspace checkout
  to read), `:missing` (checkout, no projection for that product), `:unreadable`
  (projection would not parse) or `:resolved`."
  [configuration b]
  (let [ws (business/workspace configuration)
        product (:business/canvas b)
        path (some-> product projection-path)]
    (cond
      (nil? product)
      {:schema schema :state :unbound
       :detail "この事業には canvas が紐付いていません"}

      (not= :present (:state ws))
      {:schema schema :state :unresolvable :product product :source path
       :detail (:detail ws)}

      :else
      (let [tx (read-projection ws product)]
        (cond
          (nil? tx)
          {:schema schema :state :missing :product product :source path
           :detail (str path " が workspace にありません。"
                        "superproject で `gftd canvas datoms --all` を実行すると生成されます")}

          (identical? unreadable tx)
          {:schema schema :state :unreadable :product product :source path
           :detail (str path " を読めませんでした")}

          :else
          (let [entities (filter map? tx)
                header (first (filter :projection/id entities))
                blocks (->> entities (filter :canvas/block) (sort-by :canvas/order)
                            (mapv block->wire))
                raw-hyps (->> entities (filter :hyp/id) (sort-by :hyp/id) vec)
                hyps (mapv hyp->wire raw-hyps)
                risk (riskiest raw-hyps)]
            {:schema schema :state :resolved :product product :source path
             :as-of (:projection/as-of header)
             :layer (:projection/layer header)
             :projection-source (:projection/source header)
             :blocks blocks
             :hypotheses hyps
             :riskiest-hyp (kw->str (:hyp/id risk))
             ;; The block the riskiest hypothesis is about is not derivable from
             ;; the datoms — no attribute links a hypothesis to a block — so it
             ;; is absent rather than inferred from wording.
             :riskiest-block nil
             ;; Reported, not silently trusted: the header states how many
             ;; entities the generator emitted, and a projection whose file was
             ;; truncated would disagree with it.
             :counts {:blocks (count blocks)
                      :hypotheses (count hyps)
                      :declared-blocks (:projection/blocks header)
                      :declared-hypotheses (:projection/hypotheses header)
                      :complete? (and (= (count blocks) (:projection/blocks header))
                                      (= (count hyps) (:projection/hypotheses header)))}}))))))

