(ns cloud.itonami.app.canvas
  "The lean canvas of one business, and proposals to change it.

  Phase 2 of ADR-2607309600. The read side is the folded canvas; the write side
  is a proposal, and the difference between them is the whole namespace.

  ## Reading: the fold happens once, upstream

  `90-docs/business/<product>-canvas.datoms.edn` is the FOLDED canvas — the base
  datoms with every canvas-ledger event applied — generated by `gftd canvas
  datoms` in the superproject. This namespace reads that projection and does not
  fold anything.

  That is deliberate. `gftd.canvas/apply-event` is the fold, and a second
  implementation of it here would drift: the rolling-observation window alone
  (three most recent `観測 (signal):` items per block, so a routine's hourly
  append does not bury the Problem block) is behaviour nobody would reproduce by
  reading the ledger format. The app is released on its own and cannot depend on
  that tool, so the tool emits data and the app consumes it.

  It also means the app cannot see anything the projection does not carry, and it
  says so rather than guessing: `:missing` names the file it looked for.

  ## Writing: an app proposal is not a ledger entry

  `canvas-ledger.edn` is append-only and governed — every event goes through
  `gftd.react/governor`, which can reject it. This app has no governor and no
  business writing to that file, so `propose!` records the proposal in the app's
  own store and renders the exact `gftd` command that would apply it. Nothing
  here appends to the ledger. `writes-only-locally?` states that surface and a
  test holds it, the same way `business/binds-only-locally?` does.

  ## A landed proposal is measured, not asserted

  A proposal's state is not a field somebody sets. `:awaiting-governor` means the
  value is not in the projection; `:landed` means it IS — read back out of the
  regenerated projection, which is only true after the governor accepted it and
  the projection was rebuilt. With no workspace to read, the state is
  `:unverifiable`, which is neither of the other two.

  This is the same rule `operator/register-endpoint!` applies by probing an
  endpoint instead of trusting a claim, and `funding` applies by refusing an
  unknown balance instead of reading it as zero."
  (:require [clojure.edn :as edn]
            [clojure.java.io :as io]
            [clojure.string :as str]
            [cloud.itonami.app.business :as business]
            [cloud.itonami.app.store :as store])
  (:import [java.util UUID]))

(def schema "cloud.itonami.app.canvas.v1")

(def actions
  "What a proposal may ask for. Exactly the three canvas mutations the ledger
  understands (`gftd canvas add|retract|note`) — the app does not invent a fourth
  kind of change that the governor would have no rule for."
  #{:canvas/add-item :canvas/retract-item :canvas/note})

(def ledger-authority
  "Shown beside every proposal. The app is not the governor and says so."
  (str "このアプリは canvas-ledger に書きません。"
       "提案は governor を通してから ledger に入ります。"))

(defn- refuse [type detail] (throw (ex-info detail {:type type})))

(defn- projection-path [product]
  (str "90-docs/business/" (name product) "-canvas.datoms.edn"))

