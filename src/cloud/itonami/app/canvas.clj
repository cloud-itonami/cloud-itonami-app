(defn- proposal-path [id] [:canvas-proposals id])

(defn gftd-command
  "The command that would apply this proposal, for a human or a governor run to
  copy. Rendering it is the honest alternative to an Apply button the app cannot
  back: the app knows exactly what it is asking for and does not pretend it can
  do it."
  [{:keys [proposal/action proposal/canvas-id proposal/value]}]
  (let [verb (case action
               :canvas/add-item "add"
               :canvas/retract-item "retract"
               :canvas/note "note")]
    (str "nbb 70-tools/bmc/bin/gftd.cljs canvas " verb
         " " canvas-id " " (pr-str value))))

(defn proposals
  "Every canvas proposal for this session's organization, newest first."
  [session]
  (->> (vals (get-in (store/snapshot) [:canvas-proposals] {}))
       (filter #(= (:organization-id session) (:organization-id %)))
       (sort-by :proposal/proposed-at)
       reverse
       vec))

(defn- item-present?
  "Whether the projection already carries what a proposal asked for. This is the
  only evidence the app has that a proposal landed."
  [c {:keys [proposal/action proposal/canvas-id proposal/value]}]
  (when (= :resolved (:state c))
    ;; Both sides are strings here: the proposal's canvas-id came from a form
    ;; field, and `block->wire` already stringified the projection's keyword.
    (let [block (first (filter #(= canvas-id (:id %)) (:blocks c)))]
      (case action
        :canvas/add-item (boolean (some #{value} (:items block)))
        ;; A retraction has landed when the item is gone — but only if the block
        ;; itself was found. An absent block would make every retraction read as
        ;; landed, which is the difference between 「消えた」 and 「見ていない」.
        :canvas/retract-item (and (some? block) (not (some #{value} (:items block))))
        :canvas/note (= value (:note block))))))

(defn proposal-state
  "Derived, never stored.

  `:withdrawn` is the one state a human sets, because 「もう要らない」 is not
  something the projection can show. Everything else is read back out of the
  projection: an app that stored `:landed` would be recording its own hope."
  [c proposal]
  (cond
    (:proposal/withdrawn-at proposal) :withdrawn
    (not= :resolved (:state c)) :unverifiable
    (item-present? c proposal) :landed
    :else :awaiting-governor))

(defn snapshot
  "The canvas read model for one business, with its proposals and their derived
  states."
  [configuration session business-id]
  (let [b (business/business session business-id)]
    (when b
      (let [c (canvas configuration b)
            ps (filterv #(= business-id (:proposal/business-id %)) (proposals session))]
        {:schema schema
         :business (select-keys b [:business/id :business/slug :business/name
                                   :business/canvas])
         :canvas c
         :authority ledger-authority
         :proposals (mapv (fn [p]
                            (let [st (proposal-state c p)]
                              (cond-> (proposal->wire p st)
                                ;; No command for something already landed or
                                ;; withdrawn: offering one invites re-applying an
                                ;; append-only event a second time.
                                (contains? #{:awaiting-governor :unverifiable} st)
                                (assoc :command (gftd-command p)))))
                          ps)}))))

(defn propose!
  "Record a proposal to change this business's canvas.

  Validated against the ledger's vocabulary, not against the projection: a
  proposal for a block the checkout does not have is still a real proposal, and
  refusing it would make the app unusable in the released install that has no
  checkout — the same reason `business/bind!` records an unconfirmable binding."
  [session business-id {:keys [action canvas-id value reason by]}]
  (let [b (business/business session business-id)
        action (some-> action str (str/replace #"^:" "") keyword
                       (as-> k (if (namespace k) k (keyword "canvas" (name k)))))]
    (when-not b
      (refuse :business/not-found "この organization に該当する business がありません"))
    (when-not (contains? actions action)
      (refuse :canvas/action-unsupported
              (str "action は " (str/join " / " (sort (map str actions))) " のいずれかです")))
    (when-not (:business/canvas b)
      (refuse :canvas/product-unbound
              "先に事業へ canvas (:canvas/product) を紐付けてください"))
    (let [canvas-id (some-> canvas-id str str/trim not-empty)
          value (some-> value str str/trim not-empty)]
      (when-not canvas-id
        (refuse :canvas/canvas-id-missing "canvas-id が必要です（例 cloud-itonami.problem）"))
      ;; :canvas/note replaces a note and :canvas/retract-item names the item to
      ;; remove, so all three actions carry a value. An empty one would record a
      ;; proposal that asks for nothing.
      (when-not value
        (refuse :canvas/value-missing "提案の内容が必要です"))
      (when-not (seq (str by))
        (refuse :canvas/anonymous-proposal
                "提案には提案者が必要です（誰の判断かが残らない提案は提案ではありません）"))
      (let [id (str "canvas-proposal-" (UUID/randomUUID))
            record {:schema schema
                    :proposal/id id
                    :proposal/business-id business-id
                    :organization-id (:organization-id b)
                    :proposal/product (:business/canvas b)
                    :proposal/action action
                    :proposal/canvas-id canvas-id
                    :proposal/value value
                    :proposal/reason (some-> reason str str/trim not-empty)
                    :proposal/proposed-by (str by)
                    :proposal/proposed-at (store/now)}]
        (store/transact! assoc-in (proposal-path id) record)
        record))))

(defn withdraw!
  "Record that a human dropped this proposal. The record is kept: a proposal that
  was raised and abandoned is a different fact from one that was never made, and
  the fleet's ledgers keep holds as well as commits for the same reason."
  [session proposal-id {:keys [by]}]
  (let [p (get-in (store/snapshot) (proposal-path proposal-id))]
    (when-not (and p (= (:organization-id session) (:organization-id p)))
      (refuse :canvas/proposal-not-found "該当する提案がありません"))
    (let [p' (assoc p :proposal/withdrawn-at (store/now)
                    :proposal/withdrawn-by (str by))]
      (store/transact! assoc-in (proposal-path proposal-id) p')
      p')))

(defn counts
  "How many proposals are still waiting, for the nav badge. Only what the
  projection could not account for — a landed proposal is finished work and
  padding the badge with it would make the number stop meaning anything."
  [configuration session]
  (let [ps (proposals session)
        states (map (fn [p]
                      (let [b (business/business session (:proposal/business-id p))]
                        (proposal-state (if b (canvas configuration b) {:state :unbound}) p)))
                    ps)
        f (frequencies states)]
    {:proposals (count ps)
     :awaiting (get f :awaiting-governor 0)
     :landed (get f :landed 0)
     :unverifiable (get f :unverifiable 0)
     :withdrawn (get f :withdrawn 0)}))

(defn writes-only-locally?
  "Every store path this namespace writes. The canvas ledger is not among them
  and a test asserts this vector, so adding a ledger write has to change it."
  []
  [[:canvas-proposals]])
